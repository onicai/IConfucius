const LANGUAGES = [
  { key: 'English', label: 'English' },
  { key: 'Chinese', label: '中文' },
  { key: 'Dutch', label: 'Nederlands' },
  { key: 'German', label: 'Deutsch' },
  { key: 'Hindi', label: 'हिन्दी' }, // live: Gemma-3-1B on llama_cpp_canister 0.16.8
];

function LoadingBlock({ t, elapsed, spinner }) {
  return (
    <div className="loading">
      {spinner && <div className="spinner" />}
      <p>
        {t.meditating(elapsed)}
        <br />
        <span className="hint">{t.hint}</span>
      </p>
    </div>
  );
}

export default function App() {
  const [language, setLanguage] = useState('English');
  const [topic, setTopic] = useState('');
  const [phase, setPhase] = useState('idle'); // idle | loading | done | error
  const [quote, setQuote] = useState('');
  const [quoteTopic, setQuoteTopic] = useState('');
  const [errorMsg, setErrorMsg] = useState('');
  const [paused, setPaused] = useState(false);
  const [elapsed, setElapsed] = useState(0);
  const [revealed, setRevealed] = useState(false);
  const [attempt, setAttempt] = useState(0);
  const timerRef = useRef(null);
  const t = STRINGS[language];

  useEffect(() => {
    actor
      .getPauseIconfuciusFlag()
      .then((res) => {
        if ('Ok' in res && res.Ok.flag) setPaused(true);
      })
      .catch(() => {
        // Treat a failed query as not-paused; the update call reports pause too.
      });
    return () => clearInterval(timerRef.current);
  }, []);

  useEffect(() => {
    document.documentElement.lang = t.htmlLang;
  }, [t]);

  const canGenerate = phase !== 'loading' && !paused && topic.trim() !== '';

  async function generate(e) {
    e.preventDefault();
    if (!canGenerate) return;
    setPhase('loading');
    setQuote('');
    setErrorMsg('');
    setElapsed(0);
    setRevealed(false);
    setAttempt((a) => a + 1);
    const startTime = Date.now();
    timerRef.current = setInterval(() => {
      setElapsed(Math.floor((Date.now() - startTime) / 1000));
    }, 1000);
    try {
      const res = await actor.IConfuciusSays({ [language]: null }, topic.trim());
      if ('Ok' in res) {
        setQuote(res.Ok);
        setQuoteTopic(topic.trim());
        setPhase('done');
      } else {
        setErrorMsg(apiErrorToMessage(res.Err, language));
        setPhase('error');
      }
    } catch (err) {
      setErrorMsg(t.callFailed(err.message));
      setPhase('error');
    } finally {
      clearInterval(timerRef.current);
    }
  }

  return (
    <div className="app">
      <div className="segmented">
        {LANGUAGES.map(({ key, label }) => (
          <button
            key={key}
            type="button"
            className={language === key ? 'active' : ''}
            onClick={() => setLanguage(key)}
          >
            {label}
          </button>
        ))}
      </div>

      <header>
        <img className="logo" src="/IConfucius.jpg" alt="IConfucius" />
        <h1>IConfucius</h1>
        <p className="tagline">{t.tagline}</p>
      </header>

      {paused && <div className="banner">{t.paused}</div>}

      <form onSubmit={generate}>
        <input
          type="text"
          value={topic}
          maxLength={100}
          placeholder={t.placeholder}
          onChange={(e) => setTopic(e.target.value)}
          onFocus={WEBGL_OK ? preloadCookie : undefined}
          disabled={phase === 'loading' || paused}
        />
        <button type="submit" className="generate" disabled={!canGenerate}>
          {phase === 'loading' ? t.generating : t.generate}
        </button>
      </form>

      {WEBGL_OK && (
        <Suspense fallback={null}>
          <CookieExperience
            key={attempt}
            phase={phase}
            quote={quote}
            crackLabel={t.crack}
            readyLabel={t.cookieReady}
            onRevealed={() => setRevealed(true)}
          />
        </Suspense>
      )}

      {phase === 'loading' && <LoadingBlock t={t} elapsed={elapsed} spinner={!WEBGL_OK} />}

      {phase === 'done' && (revealed || !WEBGL_OK) && (
        <blockquote className={`quote${WEBGL_OK ? ' reveal' : ''}`}>
          <p>{quote}</p>
          <footer>{t.attribution(quoteTopic)}</footer>
        </blockquote>
      )}

      {phase === 'error' && <div className="error">{errorMsg}</div>}
    </div>
  );
}
